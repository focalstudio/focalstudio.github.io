#!/usr/bin/env node
// Writes a static, crawlable page for every app in assets/apps.json: apps/<slug>.html.
// No dependencies. The page shell (nav, footer, assets) comes from app.html and the body
// from detailHtml() in assets/script.js, the same code app.html?app=<slug> renders with,
// so the two can't drift. app-pages.yml runs it on main and opens a PR with the result.
//
// Usage: node scripts/build-app-pages.mjs [--check]
//   --check  write nothing; exit 1 if any page is missing, stale or orphaned

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, unlinkSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'apps');
const CHECK = process.argv.includes('--check');

const { detailHtml, detailMeta, detailHref, esc, local, SITE_URL } = createRequire(import.meta.url)('../assets/script.js');
const { apps } = JSON.parse(readFileSync(resolve(ROOT, 'assets/apps.json'), 'utf8'));
const shell = readFileSync(resolve(ROOT, 'app.html'), 'utf8');

const META = /[ \t]*<!-- app-meta:start[\s\S]*?app-meta:end -->\n/;
const DETAIL = /[ \t]*<!-- app-detail:start[\s\S]*?app-detail:end -->\n/;
if (!META.test(shell) || !DETAIL.test(shell)) {
  console.error('✗ app.html is missing its app-meta / app-detail markers');
  process.exit(1);
}

// One folder down: relative links in the shell need ../ (anchors, absolute and external URLs don't)
const nested = shell.replace(/(\s(?:href|src)=")(?![a-z][a-z0-9+.-]*:|\/|#)/gi, '$1../');

function metaTags(app) {
  const { title, description } = detailMeta(app);
  const url = SITE_URL + detailHref(app);
  const image = new URL(local(app.icon, ''), SITE_URL).href;
  const tag = (attr, key, value) => `  <meta ${attr}="${key}" content="${esc(value)}" />`;
  return [
    '  <!-- Generated by scripts/build-app-pages.mjs from assets/apps.json. Do not edit by hand. -->',
    `  <title>${esc(title)}</title>`,
    tag('name', 'description', description),
    '  <meta name="theme-color" content="#0B0B0D" />',
    `  <link rel="canonical" href="${esc(url)}" />`,
    '  <!-- Open Graph / Twitter -->',
    tag('property', 'og:type', 'website'),
    tag('property', 'og:site_name', 'Focal Studio'),
    tag('property', 'og:url', url),
    tag('property', 'og:title', title),
    tag('property', 'og:description', description),
    tag('property', 'og:image', image),
    tag('property', 'og:image:alt', `${app.name} app icon`),
    tag('property', 'twitter:card', 'summary'),
    tag('property', 'twitter:url', url),
    tag('property', 'twitter:title', title),
    tag('property', 'twitter:description', description),
    tag('property', 'twitter:image', image),
    ''
  ].join('\n');
}

function page(app) {
  // One section per line keeps bot PR diffs readable
  const body = detailHtml(app, '../').replace(/<section /g, '\n    <section ').trimStart();
  return nested
    .replace(META, () => metaTags(app))
    .replace(DETAIL, () => `    ${body}\n`);
}

const wanted = new Map(apps.map((app) => [`${app.slug}.html`, page(app)]));
const existing = existsSync(OUT_DIR) ? readdirSync(OUT_DIR).filter((f) => f.endsWith('.html')) : [];
const changes = [];

for (const [file, html] of wanted) {
  const path = resolve(OUT_DIR, file);
  const before = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (before === html) continue;
  changes.push(`${before === null ? 'added' : 'updated'} apps/${file}`);
  if (!CHECK) {
    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(path, html);
  }
}

for (const file of existing) {
  if (wanted.has(file)) continue;
  changes.push(`removed apps/${file}`);
  if (!CHECK) unlinkSync(resolve(OUT_DIR, file));
}

if (!changes.length) {
  console.log(`✓ ${wanted.size} app pages are up to date`);
} else if (CHECK) {
  console.error(`✗ App pages are out of date. Run node scripts/build-app-pages.mjs\n  ${changes.join('\n  ')}`);
  process.exit(1);
} else {
  console.log(`✓ ${changes.join('\n✓ ')}`);
}
